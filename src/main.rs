#[derive(Debug, Serialize)]
struct AgentMessageRequest<'a> {
    pub model: &'a str,
    pub max_tokens: u32,
    pub messages: &'a [Message],
    pub tools: &'a [ToolDefinition],
}

impl<'a> AgentMessageRequest<'a> {
    pub fn new(
        model: &'a str,
        max_tokens: u32,
        messages: &'a [Message],
        tools: &'a [ToolDefinition],
    ) -> Self {
        Self {
            model,
            max_tokens,
            messages,
            tools,
        }
    }
}

#[derive(Debug, Deserialize)]
struct AgentMessageResponse {
    pub content: Vec<ContentBlock>,
}

#[derive(Debug, Serialize, Deserialize, Clone)]
#[serde(tag = "type")]
enum ContentBlock {
    #[serde(rename = "text")]
    Text { text: String },
    #[serde(rename = "tool_use")]
    ToolUse {
        id: String,
        name: String,
        input: Value,
    },
    #[serde(rename = "tool_result")]
    ToolResult {
        tool_use_id: String,
        content: String,
        #[serde(skip_serializing_if = "Option::is_none")]
        is_error: Option<bool>,
    },
}

#[derive(Debug, Serialize, Deserialize, Clone)]
struct Message {
    pub role: Role,
    pub content: MessageContent,
}

impl Message {
    pub fn user_text(content: String) -> Self {
        Self {
            role: Role::User,
            content: MessageContent::Text(content),
        }
    }

    pub fn assistant_blocks(content: Vec<ContentBlock>) -> Self {
        Self {
            role: Role::Assistant,
            content: MessageContent::Blocks(content),
        }
    }

    pub fn user_blocks(content: Vec<ContentBlock>) -> Self {
        Self {
            role: Role::User,
            content: MessageContent::Blocks(content),
        }
    }
}

#[derive(Debug, Serialize, Deserialize, Clone)]
#[serde(untagged)]
enum MessageContent {
    Text(String),
    Blocks(Vec<ContentBlock>),
}

#[derive(Debug, Serialize, Deserialize, Clone)]
#[serde(rename_all = "lowercase")]
pub enum Role {
    User,
    Assistant,
    System,
}

#[derive(Debug, Serialize, Deserialize, Default)]
struct ConversationState {
    messages: Vec<Message>,
}

#[derive(Debug, Serialize)]
struct ConversationStateRef<'a> {
    messages: &'a [Message],
}

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    let workspace_root = env::current_dir()?;
    let state_dir = workspace_root.join(STATE_DIR_NAME);
    let conversation_path = state_dir.join(CONVERSATION_STATE_FILE_NAME);

    let mut messages = match load_json_file::<ConversationState>(&conversation_path) {
        Ok(state) => {
            let mut messages = state.messages;
            if messages.len() > MAX_PERSISTED_MESSAGES {
                let overflow = messages.len() - MAX_PERSISTED_MESSAGES;
                messages.drain(0..overflow);
                eprintln!(
                    "Persisted conversation exceeded {} messages and was truncated.",
                    MAX_PERSISTED_MESSAGES
                );
            }
            messages
        }
        Err(err) => {
            eprintln!(
                "Failed to load persisted conversation '{}': {err}. Starting with an empty conversation.",
                conversation_path.display()
            );
            Vec::new()
        }
    };

    let mut input_session = match InputSession::load(state_dir.join(INPUT_HISTORY_FILE_NAME)) {
        Ok(session) => session,
        Err(err) => {
            eprintln!("Failed to load input history: {err}. Starting with empty input history.");
            InputSession {
                history_path: state_dir.join(INPUT_HISTORY_FILE_NAME),
                entries: Vec::new(),
            }
        }
    };

    let provider = ProviderKind::from_env()?;
    if provider != ProviderKind::Anthropic {
        return Err(Error::new(
            ErrorKind::Unsupported,
            format!("Provider '{provider}' is not implemented yet. Currently available: anthropic"),
        )
        .into());
    }
    let provider_capabilities = provider.capabilities();

    let api_key = env::var("ANTHROPIC_API_KEY")
        .map_err(|_| Error::new(ErrorKind::NotFound, "ANTHROPIC_API_KEY is not set"))?;
    let anthropic_version =
        env::var("ANTHROPIC_VERSION").unwrap_or_else(|_| "2023-06-01".to_string());
    let model = env::var("MODEL").unwrap_or_else(|_| "claude-sonnet-4-5".to_string());
    let max_tokens = env::var("MAX_TOKENS")
        .unwrap_or_else(|_| "1000".to_string())
        .parse::<u32>()
        .map_err(|e| {
            Error::new(
                ErrorKind::InvalidInput,
                format!("MAX_TOKENS must be an unsigned integer: {e}"),
            )
        })?;

    let tools = vec![read_file_tool(), list_files_tool(), text_editor_tool()];
    let client = reqwest::Client::builder()
        .timeout(Duration::from_secs(30))
        .build()?;

    loop {
        let Some(user_input) = parse_input(">> ", &mut input_session)? else {
            break;
        };

        let command = user_input
            .split_whitespace()
            .next()
            .unwrap_or("")
            .to_ascii_lowercase();

        match command.as_str() {
            "/exit" | "/quit" => break,
            "/clear" => {
                messages.clear();
                if let Err(err) = save_json_file(
                    &conversation_path,
                    &ConversationStateRef {
                        messages: &messages,
                    },
                ) {
                    eprintln!("Warning: failed to persist cleared conversation state: {err}");
                }
                println!("Conversation cleared.");
                continue;
            }
            _ => {}
        }

        messages.push(Message::user_text(user_input));
        run_agent_turn(
            &client,
            &api_key,
            &anthropic_version,
            &model,
            max_tokens,
            provider_capabilities.supports_tools,
            &tools,
            &workspace_root,
            &mut messages,
        )
        .await?;
        if let Err(err) = save_json_file(
            &conversation_path,
            &ConversationStateRef {
                messages: &messages,
            },
        ) {
            eprintln!("Warning: failed to persist conversation state: {err}");
        }
    }

    Ok(())
}

pub(crate) fn load_json_file<T>(path: &Path) -> io::Result<T>
where
    T: for<'de> Deserialize<'de> + Default,
{
    match fs::read_to_string(path) {
        Ok(content) => serde_json::from_str(&content).map_err(|err| {
            Error::new(
                ErrorKind::InvalidData,
                format!("Invalid JSON in '{}': {err}", path.display()),
            )
        }),
        Err(err) if err.kind() == ErrorKind::NotFound => Ok(T::default()),
        Err(err) => Err(err),
    }
}

pub(crate) fn save_json_file<T>(path: &Path, value: &T) -> io::Result<()>
where
    T: Serialize,
{
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    let serialized = serde_json::to_string_pretty(value).map_err(|err| {
        Error::other(format!(
            "Failed to serialize JSON '{}': {err}",
            path.display()
        ))
    })?;
    fs::write(path, serialized)
}

