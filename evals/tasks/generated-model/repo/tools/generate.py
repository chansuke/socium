"""Writes gen/<name>.py for each schema/<name>.json.

usage: python3 tools/generate.py [OUT_DIR]
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def render(schema, source):
    lines = [
        f"# Generated by tools/generate.py from {source}. Do not edit.",
        "from dataclasses import dataclass",
        "",
        "",
        "@dataclass",
        f"class {schema['name']}:",
        f'    """{schema["description"]}"""',
        "",
    ]
    for field in schema["fields"]:
        default = f" = {field['default']!r}" if "default" in field else ""
        lines.append(f"    # {field['description']}")
        lines.append(f"    {field['name']}: {field['type']}{default}")
    return "\n".join(lines) + "\n"


def main():
    out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "gen"
    out.mkdir(parents=True, exist_ok=True)
    for path in sorted((ROOT / "schema").glob("*.json")):
        schema = json.loads(path.read_text())
        (out / f"{path.stem}.py").write_text(render(schema, f"schema/{path.name}"))


if __name__ == "__main__":
    main()
